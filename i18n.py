"""
Internationalisation for Jharkhand Samadhan.

Design:
- English and Hindi are the two primary, fully-translated UI languages.
- A language dropdown additionally offers Jharkhand's own regional/tribal
  languages (Nagpuri, Khortha, Panchpargania, Santali, Ho, Mundari, Kurukh,
  Kharia), each with core navigation/action/status vocabulary.
- Every offered language has a `fallback` chain that ends at Hindi, so a
  language with partial coverage never breaks the UI or shows a raw key — it
  shows the best available translation (Jharkhand languages fall back to the
  fully-translated Hindi).

Honesty note: full, review-quality translation of every string into these
tribal languages needs native-speaker review before real deployment. This
file translates the core navigation, actions, and status vocabulary for the
offered languages, and falls back gracefully for anything not yet translated.

Translation dictionaries for other major Indian languages (Bengali, Odia,
Marathi, Gujarati, Punjabi, Tamil, Telugu, Kannada, Malayalam, Urdu,
Assamese) are retained further below but are NOT offered in the dropdown
until their coverage is complete — otherwise they fall back to English and
appear untranslated. Re-add them to LANGUAGES once filled in.
"""

